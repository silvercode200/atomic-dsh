#!/usr/bin/env node
// tests/fork-version.test.js — тесты патча ID.02.1 «logo-version»
// (TG-DSH-FORK-VERSION-20260918): стартовый логотип показывает версию форка
// как суффикс +p<N>, N = число записей PATCH-SERIES.
//
// КОНТРАКТ (TDD red):
//   1. apply-скрипт генерирует lib/types/components/forkVersion.js в живом
//      пакете (файл НЕ входит в реестр патчей — генерируется, не патчится):
//      export const patch = <N>, N = число записей в
//      dsh-overrides/patches/PATCH-SERIES (post-3D миграции = 75);
//   2. LogoV2.js рендерит '  v' + VERSION + forkSuffix (dimColor сохранён),
//      forkSuffix = createRequire-require('./forkVersion.js').patch → '+p<N>'
//      (пакет ESM type:module — голый require не существует; файл ESM-контента
//      грузится через require(esm), Node >= 22.12 — пиннед local/colab runtime);
//      любой сбой чтения → '' (стоковый вид);
//   3. render-проба: headless-рендер LogoV2 — на экране 'v0.10.0-beta.4+p75'.
// Запуск: node --test tests/fork-version.test.js

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, realpathSync } from 'node:fs';
import { PassThrough } from 'node:stream';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

import { importTuiModule, TUI_BASE } from './tui-base.mjs';

const live = (rel) => readFileSync(realpathSync(`${TUI_BASE}/${rel}`), 'utf8');
const repo = (rel) => readFileSync(new URL(`../${rel}`, import.meta.url), 'utf8');

/** Читает PATCH-SERIES и возвращает массив имён патчей (в порядке применения). */
const readSeries = () => {
    const raw = repo('dsh-overrides/patches/PATCH-SERIES');
    return raw.split('\n')
        .map(l => l.trim())
        .filter(l => l && !l.startsWith('#'));
};

/** fork_max = число записей PATCH-SERIES (контракт apply-скрипта). */
const forkMax = () => readSeries().length;

// ── (a) юнит: PATCH-SERIES + реестр + согласованность forkVersion.js ──

test('PATCH-SERIES: 75 записей (post-3D миграции SUBSYS.FF.B)', () => {
    const series = readSeries();
    assert.ok(series.length >= 50, `PATCH-SERIES >= 50 записей, найдено ${series.length}`);
    assert.strictEqual(series.length, 75, `PATCH-SERIES = 75 записей (post-3D), получено ${series.length}`);
    // MS.01.1 (squashed 26b+54+77+79) присутствует в серии
    assert.ok(series.includes('MS.01.1-scroll-menu-nogap.patch'),
        'MS.01.1-scroll-menu-nogap.patch в PATCH-SERIES');
    // ID.02.1-logo-version.patch присутствует в серии
    assert.ok(series.includes('ID.02.1-logo-version.patch'),
        'ID.02.1-logo-version.patch в PATCH-SERIES');
});

test('реестр apply-скрипта: ID.02.1-logo-version.patch зарегистрирован, fork_max = SERIES length', () => {
    const script = repo('scripts/apply-dsh-overrides.sh');
    const series = readSeries();
    // записи реестра MARKERS: [NN-name.patch]=
    const names = [...script.matchAll(/\[\s*([\w.-]+\.patch)\s*\]\s*=/g)].map(m => m[1]);
    assert.ok(names.length >= 50, `в реестре >= 50 записей, найдено ${names.length}`);
    assert.ok(names.includes('ID.02.1-logo-version.patch'), 'ID.02.1-logo-version.patch в реестре MARKERS');
    // маркер и целевой файл wired
    assert.ok(script.includes("[ID.02.1-logo-version.patch]='dsh-overrides 49: fork version suffix'"), 'маркер 49 объявлен');
    assert.match(script, /ID\.02\.1-logo-version\.patch\)\s*printf '%s' 'lib\/types\/components\/LogoV2\.js'/, 'marker_file ID.02.1 → LogoV2.js');
    // fork_max берётся из SERIES length, не хардкодится (post-migration)
    assert.match(script, /local fork_max="\$\{#SERIES_PATCHES\[@\]\}"/,
        'fork_max = SERIES_PATCHES array length (post-migration контракт)');
});

test('forkVersion.js живого пакета: сгенерирован, patch = SERIES length (75), не патчится', () => {
    const script = repo('scripts/apply-dsh-overrides.sh');
    const names = [...script.matchAll(/\[\s*([\w.-]+\.patch)\s*\]\s*=/g)].map(m => m[1]);
    const max = forkMax();
    const fv = live('lib/types/components/forkVersion.js');
    // ESM-контент: пакет type:module, LogoV2 грузит файл через require(esm).
    assert.match(fv, new RegExp(`export const patch = ${max};`), `forkVersion.js: patch = ${max}`);
    assert.match(fv, /export const generatedAt = '/, 'generatedAt (UTC) присутствует');
    assert.match(fv, /Generated by scripts\/apply-dsh-overrides\.sh/, 'файл помечен как генерируемый');
    // мета-файл НЕ входит в реестр патчей (генерируется, не патчится)
    assert.ok(!names.includes('forkVersion.js'), 'forkVersion.js не запись реестра');
});

// ── source-level: LogoV2.js читает forkVersion с fallback, суффикс в рендере ──

test('LogoV2.js: рендер версии + forkSuffix (dimColor), чтение через createRequire с fallback', () => {
    const src = live('lib/types/components/LogoV2.js');
    // суффикс прицеплен к версии, dimColor и wrap truncate-end сохранены
    assert.ok(src.includes("_jsx(Text, { dimColor: true, children: '  v' + VERSION + forkSuffix })"),
        "версия рендерится как '  v' + VERSION + forkSuffix с dimColor");
    const idx = src.indexOf("'  v' + VERSION + forkSuffix");
    assert.ok(idx > 0 && src.slice(Math.max(0, idx - 200), idx).includes('wrap: "truncate-end"'),
        'родительский Text сохранил wrap truncate-end');
    // чтение: createRequire (пакет ESM — голого require нет) + try/catch fallback
    assert.ok(src.includes('createRequire(import.meta.url)'), 'require создан через createRequire');
    assert.ok(src.includes("req('./forkVersion.js').patch"), "require('./forkVersion.js').patch");
    const fsIdx = src.indexOf('const forkSuffix = (() => {');
    assert.ok(fsIdx > 0, 'forkSuffix вычисляется с fallback-обёрткой');
    assert.ok(src.slice(fsIdx, fsIdx + 400).includes('catch'), 'try/catch fallback на случай отсутствия файла');
});

// ── (b) render-проба: живой LogoV2 на экране показывает +p75 ────────────────

test('render-проба: логотип показывает v0.10.0-beta.4+p<SERIES length>', async () => {
    const LIB = `${realpathSync(TUI_BASE)}/lib/types`;
    const pkgRequire = createRequire(`${LIB}/components/LogoV2.js`);
    const React = pkgRequire('react');
    const { renderSync } = await importTuiModule('lib/types/ink/root.js');
    const { ThemeProvider } = await importTuiModule('lib/types/ui.js');
    const { LogoV2 } = await importTuiModule('lib/types/components/LogoV2.js');
    const { setLang } = await importTuiModule('lib/types/i18n.js');
    const instances = (await importTuiModule('lib/types/ink/instances.js')).default;
    const { cellAt } = await importTuiModule('lib/types/ink/screen.js');
    setLang('en');

    const makeTty = () => {
        const out = new PassThrough();
        out.isTTY = true; out.columns = 100; out.rows = 30;
        out.setRawMode = () => { };
        return out;
    };
    const stdout = makeTty();
    const stdin = makeTty();
    stdin.isRaw = true;
    stdin.ref = () => { }; stdin.unref = () => { };
    // skipIntro: settled-кадр без анимации; whale=false — текстовая колонка.
    const tree = React.createElement(ThemeProvider, { theme: 'dark' },
        React.createElement(LogoV2, { model: 'glm-5.3', effort: 'high', cwd: '/tmp', skipIntro: true, whale: false }));
    const inst = renderSync(tree, { stdout, stdin, exitOnCtrlC: false, patchConsole: false });
    try {
        await new Promise(r => setTimeout(r, 400));
        const ink = instances.get(stdout);
        const screen = ink?.frontFrame?.screen;
        assert.ok(screen, 'экран отрендерен (frontFrame.screen)');
        const lines = [];
        for (let y = 0; y < screen.height; y++) {
            let line = '';
            for (let x = 0; x < screen.width; x++) {
                const c = cellAt(screen, x, y);
                if (!c) break;
                line += c.char;
            }
            lines.push(line);
        }
        const wordmark = lines.find(l => l.includes('dsh-TUI'));
        assert.ok(wordmark !== undefined, `строка wordmark найдена, кадр: ${JSON.stringify(lines.filter(l => l.trim() !== '').slice(0, 3))}`);
        console.log(`render: ${wordmark.replace(/\s+$/g, '')}`);
        const max2 = forkMax();
        const expect = `v0.10.0-beta.4+p${max2}`;
        assert.ok(wordmark.includes(expect),
            `wordmark содержит версию форка +p${max2}, получено: ${wordmark}`);
    }
    finally {
        inst.unmount();
    }
});
